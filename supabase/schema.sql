-- StudyForge v1: eenmalig uitvoeren in de Supabase SQL Editor.
-- Een geauthenticeerd gezinsaccount met twee profielen: Nikki (1) en Dean (2).
-- RLS scheidt gezinnen/accounts, NIET de kinderen binnen een gedeeld account.

create table if not exists public.sf_collections (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  profile_id smallint not null check (profile_id in (1, 2)),
  type text not null check (type in ('quiz', 'flashcards')),
  subject text not null,
  title text not null,
  description text not null default '',
  count integer not null check (count between 1 and 250),
  content jsonb not null,
  created_at timestamptz not null default now()
);
create index if not exists sf_collections_owner_profile on public.sf_collections(owner_id, profile_id, created_at desc);

create table if not exists public.sf_attempts (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  profile_id smallint not null check (profile_id in (1, 2)),
  collection_id bigint not null references public.sf_collections(id) on delete cascade,
  title text not null,
  subject text not null,
  correct_count integer not null check (correct_count >= 0),
  total_count integer not null check (total_count > 0),
  grade numeric(3,1) not null check (grade >= 1 and grade <= 10),
  details jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists sf_attempts_owner_profile on public.sf_attempts(owner_id, profile_id, created_at desc);

create table if not exists public.sf_reviews (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  profile_id smallint not null check (profile_id in (1, 2)),
  collection_id bigint not null references public.sf_collections(id) on delete cascade,
  card_index integer not null check (card_index >= 0),
  known smallint not null check (known in (0, 1)),
  reviews integer not null default 0 check (reviews >= 0),
  created_at timestamptz not null default now(),
  unique (owner_id, collection_id, card_index)
);
create index if not exists sf_reviews_owner_profile on public.sf_reviews(owner_id, profile_id);

alter table public.sf_collections enable row level security;
alter table public.sf_attempts enable row level security;
alter table public.sf_reviews enable row level security;

-- Publieke anonieme database-toegang expliciet uitschakelen.
revoke all on public.sf_collections, public.sf_attempts, public.sf_reviews from anon;

drop policy if exists sf_collections_owner on public.sf_collections;
create policy sf_collections_owner on public.sf_collections
for all to authenticated using (owner_id = (select auth.uid()))
with check (owner_id = (select auth.uid()));

drop policy if exists sf_attempts_owner on public.sf_attempts;
create policy sf_attempts_owner on public.sf_attempts
for all to authenticated using (owner_id = (select auth.uid()))
with check (owner_id = (select auth.uid()));

drop policy if exists sf_reviews_owner on public.sf_reviews;
create policy sf_reviews_owner on public.sf_reviews
for all to authenticated using (owner_id = (select auth.uid()))
with check (owner_id = (select auth.uid()));

-- De Data API is aan, maar automatische grants staan uit.
-- Daarom enkel expliciete toegang voor ingelogde gebruikers geven.
grant select, insert, update, delete on public.sf_collections to authenticated;
grant select, insert, update, delete on public.sf_attempts to authenticated;
grant select, insert, update, delete on public.sf_reviews to authenticated;
grant usage, select on sequence public.sf_collections_id_seq to authenticated;
grant usage, select on sequence public.sf_attempts_id_seq to authenticated;
grant usage, select on sequence public.sf_reviews_id_seq to authenticated;

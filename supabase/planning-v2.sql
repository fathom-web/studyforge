-- StudyForge uitbreiding v2: planning, leerdoelen en synchronisatie van gepubliceerde toetsen.
-- Eénmalig uitvoeren NADAT het bestaande supabase/schema.sql is uitgevoerd.
-- Het reguliere gezinsaccount blijft nodig om eigen voortgang tussen apparaten te synchroniseren.

alter table public.sf_collections
  add column if not exists source_key text;
create unique index if not exists sf_collections_owner_source_key
  on public.sf_collections(owner_id, source_key)
  where source_key is not null;

create table if not exists public.sf_study_state (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  profile_id smallint not null check (profile_id in (1,2)),
  payload jsonb not null default '{"exams":[],"goals":{"sessionsPerWeek":3,"targetGrade":7},"completed":{}}'::jsonb,
  updated_at timestamptz not null default now(),
  unique(owner_id, profile_id)
);

create index if not exists sf_study_state_owner_profile
  on public.sf_study_state(owner_id,profile_id);

alter table public.sf_study_state enable row level security;
revoke all on public.sf_study_state from anon;
drop policy if exists sf_study_state_owner on public.sf_study_state;
create policy sf_study_state_owner
  on public.sf_study_state for all to authenticated
  using (owner_id = (select auth.uid()))
  with check (owner_id = (select auth.uid()));
grant select,insert,update,delete on public.sf_study_state to authenticated;
grant usage,select on sequence public.sf_study_state_id_seq to authenticated;

